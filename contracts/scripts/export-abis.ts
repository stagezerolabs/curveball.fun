// Writes the lean singletons' ABIs from forge artifacts into the SDK. Run `forge build` first.
const contracts = {
  curveLaunchpadAbi: "CurveLaunchpad",
  curveFeeEscrowAbi: "CurveFeeEscrow",
  curveLpLockerAbi: "CurveLpLocker",
  curveHolderReserveAbi: "CurveHolderReserve",
  curveTokenAbi: "CurveToken",
} as const;
const outputPath = new URL("../../src/sdk/abis.generated.ts", import.meta.url).pathname;

let source = "// Generated by contracts/scripts/export-abis.ts from forge artifacts. Do not edit.\n";
for (const [exportName, contractName] of Object.entries(contracts)) {
  const artifactPath = new URL(`../out/${contractName}.sol/${contractName}.json`, import.meta.url).pathname;
  const artifact = await Bun.file(artifactPath).json() as { abi: unknown[] };
  source += `\nexport const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
}
await Bun.write(outputPath, source);
console.log(`Wrote ${Object.keys(contracts).length} ABIs to src/sdk/abis.generated.ts.`);
