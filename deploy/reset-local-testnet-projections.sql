  SELECT 1 FROM curveball.contract_deployments
  WHERE chain_id = 11155931 AND lower(address) <> lower(:'new_launchpad')
) OR EXISTS (
  SELECT 1 FROM curveball.markets
  WHERE chain_id = 11155931 AND lower(launchpad_address) <> lower(:'new_launchpad')
) AS reset_required \gset

